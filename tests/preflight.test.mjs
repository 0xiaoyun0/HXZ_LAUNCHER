import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {preflight} from '../engine/preflight.mjs';
import {readVersion} from '../packages/engine/core/minecraft.mjs';
const runtime={path:'synthetic-java',architecture:'x64',major:17,version:'17.0.11'};
const tools={readVersion,architecture:()=>'x64',findJava:async()=>[runtime],inspectJava:async()=>runtime};
test('preflight follows inherited metadata and respects the selected instance, Java and role',async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'hxz-check-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const write=async(id,data)=>{const p=path.join(dir,'versions',id);await fs.mkdir(p,{recursive:true});await fs.writeFile(path.join(p,id+'.json'),JSON.stringify(data));};
 await write('1.18.2',{id:'1.18.2',javaVersion:{majorVersion:17},mainClass:'local.main'});
 await write('survival',{id:'survival',inheritsFrom:'1.18.2',jar:'1.18.2'});
 const jar=path.join(dir,'versions/1.18.2/1.18.2.jar');await fs.writeFile(jar,'fixture');
 const snapshot={accounts:[{id:'player',uuid:'role',authenticated:true}],instances:[{id:'survival',name:'生存服',installed:true}],settings:{gameRoot:dir,selectedAccount:'player',instanceSettings:{}}};
 const run=async(replace={})=>(await preflight(snapshot,'survival',{tools:{...tools,...replace}})).checks;
 let rows=await run();assert.deepEqual(rows.map(v=>v.status),['ok','ok','ok','ok','ok']);assert.equal(await fs.readFile(jar,'utf8'),'fixture');
 await fs.unlink(jar);rows=await run();assert.equal(rows[1].status,'needs');assert.equal(rows[1].action,'library');
 await write('survival',{id:'survival',inheritsFrom:'1.18.2',jar:'1.18.2',downloads:{client:{url:'https://example.invalid/game.jar'}}});
 rows=await run();assert.equal(rows[1].status,'info');
 snapshot.settings.instanceSettings.survival={javaMode:'custom',javaPath:'missing'};
 rows=await run({inspectJava:async()=>{throw Error('找不到所选 Java');},findJava:async()=>assert.fail('manual selection must remain visible')});
 assert.equal(rows[2].status,'needs');assert.equal(rows[2].action,'java');
 snapshot.settings.instanceSettings.survival={javaMode:'auto'};
 rows=await run({findJava:async()=>[{...runtime,major:21}]});assert.equal(rows[2].status,'needs');
 snapshot.accounts=[];snapshot.settings.gameRoot=path.join(dir,'absent');
 rows=await run();assert.deepEqual(rows.map(v=>v.status),['needs','unknown','unknown','needs','ok']);assert.equal(rows[3].action,'account');
 await assert.rejects(preflight(snapshot,'deleted',{tools}),/重新选择/);
});
